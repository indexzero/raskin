use clap::{CommandFactory, Parser, Subcommand, ValueHint};
use raskin::{
    Error, Reason, Result, artifact,
    capture::{self, CaptureReport, Preset},
    codec,
    render::{self, GenerateOptions},
    selection::{FilePreset, Selection},
};
use std::{
    io::{Read, Write},
    path::{Path, PathBuf},
    process::ExitCode,
};

#[derive(Parser)]
#[command(
    version,
    about = "Read macOS preferences into KDL and generate native commands",
    long_about = "Capture persisted macOS preferences as editable KDL, then generate a standalone .macos file. Raskin never executes generated commands. Capture defaults to apple: macOS system categories plus Terminal. Select a built-in category, use broad for wider stores, or pass -p FILE to capture exact keys from a KDL preset.",
    arg_required_else_help = true,
    after_help = "Examples:\n  raskin capture -o myprefs.kdl\n  raskin capture -p desktop -o desktop.kdl\n  raskin capture -p my-preset.kdl -o selected.kdl\n  raskin generate myprefs.kdl -o myprefs.macos\n\nReview the generated file before running it yourself. See docs/coverage.md for limits."
)]
struct Cli {
    /// Emit the jdx/usage interface specification.
    #[arg(long, hide = true)]
    usage_spec: bool,
    #[command(subcommand)]
    command: Option<Commands>,
}
#[derive(Subcommand)]
enum Commands {
    #[command(
        about = "Read persisted preferences into KDL",
        long_about = "Read explicit persisted user, host, system and container preferences plus native power profiles. Only settings supported by generation enter KDL; unavailable or unsupported settings are omitted and summarized on stderr. No settings are changed. With --from, only the supplied offline tree is read; there is no live fallback.",
        after_help = "Examples:\n  raskin capture -p input -o input.kdl\n  raskin capture -p my-preset.kdl -o selected.kdl\n  raskin capture --from ./saved-inputs -o saved.kdl"
    )]
    Capture {
        /// Show per-source capture diagnostics on stderr.
        #[arg(short, long)]
        verbose: bool,
        /// Select a built-in preset or a KDL file listing exact keys.
        #[arg(short, long, value_name="NAME_OR_FILE", value_hint=ValueHint::FilePath,
            default_value=Preset::default().as_str(), long_help=preset_help())]
        preset: PathBuf,
        /// Read an offline tree containing user/, system/, containers/, host-id.txt, and pmset.txt.
        #[arg(long, value_name="DIRECTORY", value_hint=ValueHint::DirPath)]
        from: Option<PathBuf>,
        /// Write KDL to this path; otherwise use stdout.
        #[arg(short, long, value_name="FILE", value_hint=ValueHint::FilePath)]
        output: Option<PathBuf>,
        /// Atomically replace an existing output file.
        #[arg(long, requires = "output")]
        force: bool,
    },
    #[command(
        about = "Generate a standalone .macos file from saved KDL",
        long_about = "Validate saved KDL and emit native commands for a human to inspect and run. Generation never reads host settings or executes commands. Supported settings are generated by default; unsupported settings are skipped and summarized. Use --strict to fail before output if any setting is unsupported.",
        after_help = "Examples:\n  raskin generate myprefs.kdl -o myprefs.macos\n  raskin generate myprefs.kdl --strict -o myprefs.macos\n  raskin generate - < myprefs.kdl"
    )]
    Generate {
        /// Show per-setting generation diagnostics on stderr.
        #[arg(short, long)]
        verbose: bool,
        /// KDL input path, or - to read stdin.
        #[arg(value_hint=ValueHint::FilePath)]
        input: PathBuf,
        /// Write the script to this path; otherwise use stdout.
        #[arg(short, long, value_name="FILE", value_hint=ValueHint::FilePath)]
        output: Option<PathBuf>,
        /// Atomically replace an existing output file.
        #[arg(long, requires = "output")]
        force: bool,
        /// Fail before writing if any setting is unsupported.
        #[arg(long)]
        strict: bool,
        /// Compatibility option: unsupported settings are already skipped by default.
        #[arg(long, hide = true, conflicts_with = "strict")]
        skip_unsupported: bool,
    },
}
fn main() -> ExitCode {
    let cli = Cli::parse();
    let verbose = matches!(&cli.command, Some(Commands::Generate { verbose: true, .. }));
    match run(cli) {
        Ok(()) => ExitCode::SUCCESS,
        Err(Error::Io { source, .. }) if source.kind() == std::io::ErrorKind::BrokenPipe => {
            ExitCode::SUCCESS
        }
        Err(Error::Unsupported(failures)) => {
            eprintln!("error: generation stopped; no output was written.\n{failures}");
            if verbose {
                for diagnostic in &failures.diagnostics {
                    eprintln!("{diagnostic}");
                }
            } else {
                eprintln!("Use --verbose for per-setting details.");
            }
            eprintln!("Omit --strict to generate the supported settings.");
            ExitCode::FAILURE
        }
        Err(error) => {
            eprintln!("error: {error}");
            ExitCode::FAILURE
        }
    }
}
fn run(cli: Cli) -> Result<()> {
    if cli.usage_spec {
        let mut spec = Vec::new();
        clap_usage::generate(&mut Cli::command(), "raskin", &mut spec);
        while spec.last() == Some(&b'\n') {
            spec.pop();
        }
        spec.push(b'\n');
        return emit(None, &spec, false, false);
    }
    match cli.command {
        Some(Commands::Capture {
            verbose,
            preset,
            from,
            output,
            force,
        }) => {
            let (selection, label) = capture_selection(&preset, output.as_deref())?;
            let report = match from {
                Some(root) => capture::capture_offline(&root, selection)?,
                None => capture::capture_live(selection)?,
            };
            let text = codec::encode(&report.document)?;
            emit(output.as_deref(), text.as_bytes(), force, false)?;
            capture_summary(&report, output.as_deref(), &label, verbose);
            Ok(())
        }
        Some(Commands::Generate {
            verbose,
            input,
            output,
            force,
            strict,
            skip_unsupported: _,
        }) => {
            if input != Path::new("-")
                && let Some(path) = &output
            {
                artifact::reject_alias(&input, path)?;
            }
            let mut bytes = Vec::new();
            let limit = raskin::model::MAX_DOCUMENT_BYTES as u64 + 1;
            if input == Path::new("-") {
                std::io::stdin()
                    .take(limit)
                    .read_to_end(&mut bytes)
                    .map_err(|e| Error::io("read input", "<stdin>", e))?;
            } else {
                std::fs::File::open(&input)
                    .and_then(|f| f.take(limit).read_to_end(&mut bytes))
                    .map_err(|e| Error::io("read input", &input, e))?;
            }
            if bytes.len() > raskin::model::MAX_DOCUMENT_BYTES {
                return Err(Error::Invalid("input exceeds the 128 MiB limit".into()));
            }
            let text = String::from_utf8(bytes).map_err(|e| {
                Error::Invalid(format!("{}: KDL must be UTF-8: {e}", input.display()))
            })?;
            let document = codec::decode(&text, &input.to_string_lossy())?;
            let generated = render::generate(
                &document,
                GenerateOptions {
                    skip_unsupported: !strict,
                },
            )?;
            emit(output.as_deref(), generated.script.as_bytes(), force, true)?;
            generation_summary(
                &generated,
                output.as_deref(),
                document.unavailable.len(),
                verbose,
            );
            Ok(())
        }
        None => Err(Error::Invalid(
            "choose capture or generate; see --help".into(),
        )),
    }
}
fn preset_help() -> String {
    format!(
        "Select a built-in preset or a KDL file listing exact keys. A file defines the complete selection.\n\nBuilt-in presets: {}\n\nUse ./NAME for a file whose name matches a built-in preset.",
        Preset::all()
            .map(Preset::as_str)
            .collect::<Vec<_>>()
            .join(" ")
    )
}

fn capture_selection(input: &Path, output: Option<&Path>) -> Result<(Selection, String)> {
    if let Some(preset) = input.to_str().and_then(|name| name.parse::<Preset>().ok()) {
        return Ok((preset.into(), preset.to_string()));
    }
    if let Some(output) = output {
        artifact::reject_alias(input, output)?;
    }
    let mut bytes = Vec::new();
    std::fs::File::open(input)
        .and_then(|file| {
            file.take(raskin::model::MAX_DOCUMENT_BYTES as u64 + 1)
                .read_to_end(&mut bytes)
        })
        .map_err(|error| Error::io("read preset", input, error))?;
    if bytes.len() > raskin::model::MAX_DOCUMENT_BYTES {
        return Err(Error::Invalid(
            "preset exceeds the 128 MiB input limit".into(),
        ));
    }
    let text = String::from_utf8(bytes).map_err(|error| {
        Error::Invalid(format!(
            "{}: preset KDL must be UTF-8: {error}",
            input.display()
        ))
    })?;
    let preset = FilePreset::decode(&text, &input.to_string_lossy())?;
    Ok((preset.into(), format!("{input:?}")))
}

fn emit(path: Option<&Path>, bytes: &[u8], force: bool, executable: bool) -> Result<()> {
    match path {
        Some(path) => artifact::write(path, bytes, force, executable),
        None => std::io::stdout()
            .lock()
            .write_all(bytes)
            .map_err(|e| Error::io("write stdout", "<stdout>", e)),
    }
}

/// Summaries belong on stderr, and only after the artifact was written.
fn capture_summary(report: &CaptureReport, output: Option<&Path>, preset: &str, verbose: bool) {
    let partial = if report.omissions.is_empty() {
        ""
    } else {
        "partial "
    };
    match output {
        Some(path) => eprintln!("Saved {partial}capture to {path:?}."),
        None => eprintln!("Wrote {partial}capture to stdout."),
    }
    let keys: usize = report
        .document
        .domains
        .values()
        .chain(report.document.power.values())
        .map(|values| values.len())
        .sum();
    let profiles = if report.document.power.is_empty() {
        "none".to_owned()
    } else {
        report
            .document
            .power
            .keys()
            .cloned()
            .collect::<Vec<_>>()
            .join(", ")
    };
    eprintln!(
        "Captured {keys} settings across {} preference domains; power profiles: {profiles}. Preset: {preset}.",
        report.document.domains.len()
    );
    if !report.omissions.is_empty() {
        let counts = [
            (Reason::PermissionDenied, "permission denied"),
            (Reason::Unsupported, "unsupported"),
            (Reason::Missing, "missing"),
            (Reason::ReadFailed, "read failures"),
        ]
        .into_iter()
        .filter_map(|(reason, label)| {
            let count = report
                .omissions
                .iter()
                .filter(|entry| entry.reason == reason)
                .count();
            (count > 0).then(|| format!("{count} {label}"))
        })
        .collect::<Vec<_>>()
        .join(", ");
        eprintln!("Skipped sources/fields: {counts}.");
    }
    let failed_profiles = ["battery", "charger", "ups"]
        .into_iter()
        .filter(|profile| {
            report.omissions.iter().any(|entry| {
                entry.reason == Reason::ReadFailed && entry.source == format!("pmset:{profile}")
            })
        })
        .collect::<Vec<_>>();
    if !failed_profiles.is_empty() {
        eprintln!(
            "Power profiles not captured: {}.",
            failed_profiles.join(", ")
        );
    }
    if verbose {
        for message in &report.diagnostics {
            eprintln!("{message}");
        }
    } else if !report.omissions.is_empty() {
        eprintln!("Use --verbose for per-source diagnostics.");
    }
}

/// Keep ordinary diagnostics bounded even for broad captures with many unsupported values.
fn generation_summary(
    generated: &render::Generated,
    output: Option<&Path>,
    capture_unavailable: usize,
    verbose: bool,
) {
    let partial = if generated.unsupported.is_empty() && capture_unavailable == 0 {
        ""
    } else {
        "partial "
    };
    match output {
        Some(path) => eprintln!("Saved {partial}script to {path:?}."),
        None => eprintln!("Wrote {partial}script to stdout."),
    }
    eprintln!("Generated {} settings.", generated.settings);
    if !generated.unsupported.is_empty() {
        eprintln!("Skipped {}", generated.unsupported);
    }
    if capture_unavailable > 0 {
        eprintln!("Input records {capture_unavailable} unavailable capture sources.");
    }
    if verbose {
        for message in &generated.diagnostics {
            eprintln!("{message}");
        }
    } else if !generated.diagnostics.is_empty() {
        eprintln!(
            "Use --verbose for per-setting details; omissions are also listed in script comments."
        );
    }
}
